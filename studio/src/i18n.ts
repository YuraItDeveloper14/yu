export type Key = keyof typeof UK;

/** The interface text for `key`; `{name}` blanks are filled from `values`. */
export function text(lang: YuLang, key: Key, values: Record<string, string | number> = {}): string {
  return (lang === 'uk' ? UK : EN)[key].replace(/\{(\w+)\}/g, (blank, name: string) =>
    name in values ? String(values[name]) : blank,
  );
}

